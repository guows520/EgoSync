// Story 15.5：TS 侧传输生成物（capabilities.ts / events.ts）机械导出器。
//
// 同源生成（禁手写双清单）：
// - `crates/egosync-engine/commands.json` → web-ok 命令全名单 + replayWhitelist；
// - `crates/egosync-engine/src/capabilities.rs` → desktop-only / perf-test 门控名单；
// - `crates/egosync-engine/src/events.rs` → 事件名常量（唯一发射源）。
//
// 生成物提交入库；CI 新鲜度门禁 = regenerate + `git diff --exit-code`
// （与 commands.json/dispatch_gen 同范式）。运行：`npm run gen:transport`。
//
// events.rs 正则解析器同时导出供 vitest import（单一解析器同源——
// 测试与生成器不得各写一套解析逻辑）。

import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, '..');
const repoRoot = path.resolve(appRoot, '..');

const COMMANDS_JSON = path.join(repoRoot, 'crates/egosync-engine/commands.json');
const CAPABILITIES_RS = path.join(repoRoot, 'crates/egosync-engine/src/capabilities.rs');
const EVENTS_RS = path.join(repoRoot, 'crates/egosync-engine/src/events.rs');

const OUT_CAPABILITIES = path.join(appRoot, 'src/transport/capabilities.ts');
const OUT_EVENTS = path.join(appRoot, 'src/transport/events.ts');

/**
 * 解析 events.rs 的事件名常量（`pub const *_EVENT: &str = "..."`）。
 * 返回 [{ constName, eventName }]，保持源码声明序（确定性）。
 * 格式变化导致零命中 ⇒ 抛错（宁可响亮失败，不静默产出空清单）。
 */
export function parseEngineEvents(source) {
  const re = /pub const (\w+_EVENT): &str = "([^"]+)"/g;
  const entries = [...source.matchAll(re)].map((m) => ({
    constName: m[1],
    eventName: m[2],
  }));
  if (entries.length === 0) {
    throw new Error('events.rs 正则解析零命中（格式变化？）——拒绝生成空清单');
  }
  const names = new Set(entries.map((e) => e.eventName));
  if (names.size !== entries.length) {
    throw new Error('events.rs 解析出重复事件名——常量值冲突');
  }
  return entries;
}

/**
 * 解析 capabilities.rs 的 `pub const NAME: &[&str] = &[...]` 字符串数组
 * 常量（保持源码序）。零命中 ⇒ 抛错（宁可响亮失败）。
 */
export function parseConstList(source, constName) {
  const re = new RegExp(
    `pub const ${constName}: &\\[&str\\] = &\\[([\\s\\S]*?)\\];`
  );
  const m = source.match(re);
  if (!m) {
    throw new Error(`capabilities.rs 未找到常量 ${constName}（格式变化？）`);
  }
  const items = [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
  if (items.length === 0) {
    throw new Error(`capabilities.rs 常量 ${constName} 解析为零条——拒绝生成空清单`);
  }
  return items;
}

/** 读 commands.json 工件：web-ok 命令名 + replayWhitelist。 */
export function readCommandsArtifact(jsonPath = COMMANDS_JSON) {
  const doc = JSON.parse(readFileSync(jsonPath, 'utf8'));
  // 守卫先于 map（评审 G9）：doc.commands 键缺失时不得裸抛 TypeError
  if (!Array.isArray(doc.commands) || doc.commands.length === 0) {
    throw new Error('commands.json 工件缺 commands 数组（生成物损坏？重跑 gen_commands）');
  }
  const commands = doc.commands.map((c) => c.name);
  // 字段缺失报错；空数组合法（未来白名单清空的正当终态，不误报「缺字段」）
  if (!Array.isArray(doc.replayWhitelist)) {
    throw new Error('commands.json 工件缺 replayWhitelist 字段（旧工件？重跑 gen_commands）');
  }
  const replayWhitelist = doc.replayWhitelist;
  return { commands, replayWhitelist };
}

/** 生成 capabilities.ts 源文本（确定性输出：无时间戳）。 */
export function generateCapabilitiesModule({ commands, desktopOnly, perfTestGated, replayWhitelist }) {
  const lines = [];
  lines.push('// AUTO-GENERATED by `npm run gen:transport` —— 请勿手改。');
  lines.push('//');
  lines.push('// Story 15.5 TS 侧能力清单（同源生成，禁手写双清单）：');
  lines.push(`// - web-ok 命令（${commands.length} 条）：crates/egosync-engine/commands.json 工件；`);
  lines.push(`// - desktop-only（${desktopOnly.length} 条）/ perf-test 门控（${perfTestGated.length} 条）：crates/egosync-engine/src/capabilities.rs；`);
  lines.push(`// - 重连重放白名单（${replayWhitelist.length} 条）：commands.json 顶层 replayWhitelist（engine RECONNECT_REPLAY_COMMANDS 单源导出）。`);
  lines.push('');
  lines.push("import type { TransportCapabilities } from './types';");
  lines.push('');
  lines.push(`/** web-ok 命令全名单（双宿主可用，${commands.length} 条）。 */`);
  lines.push('export const WEB_OK_COMMANDS: readonly string[] = [');
  for (const name of commands) lines.push(`  '${name}',`);
  lines.push('];');
  lines.push('');
  lines.push(`/** desktop-only 命令名单（仅 Tauri 宿主注册，${desktopOnly.length} 条）。 */`);
  lines.push('export const DESKTOP_ONLY_COMMANDS: readonly string[] = [');
  for (const name of desktopOnly) lines.push(`  '${name}',`);
  lines.push('];');
  lines.push('');
  lines.push(`/** perf-test 门控命令名单（基准构建专用，${perfTestGated.length} 条）。 */`);
  lines.push('export const PERF_TEST_GATED_COMMANDS: readonly string[] = [');
  for (const name of perfTestGated) lines.push(`  '${name}',`);
  lines.push('];');
  lines.push('');
  lines.push(`/** 重连补齐重放白名单（只读 query，${replayWhitelist.length} 条）。 */`);
  lines.push('export const REPLAY_WHITELIST: readonly string[] = [');
  for (const name of replayWhitelist) lines.push(`  '${name}',`);
  lines.push('];');
  lines.push('');
  lines.push('/** 查询某命令是否 web-ok（双宿主可用）。 */');
  lines.push('export function isWebCommand(command: string): boolean {');
  lines.push('  return WEB_OK_COMMANDS.includes(command);');
  lines.push('}');
  lines.push('');
  lines.push('/** 查询某命令是否 desktop-only（浏览器分支 UI 按 capability 隐入口）。 */');
  lines.push('export function isDesktopOnly(command: string): boolean {');
  lines.push('  return DESKTOP_ONLY_COMMANDS.includes(command);');
  lines.push('}');
  lines.push('');
  lines.push('/** 传输层能力清单对象（TauriTransport / HttpTransport 共享单源）。 */');
  lines.push('export const TRANSPORT_CAPABILITIES: TransportCapabilities = {');
  lines.push('  webCommands: WEB_OK_COMMANDS,');
  lines.push('  desktopOnlyCommands: DESKTOP_ONLY_COMMANDS,');
  lines.push('  perfTestGatedCommands: PERF_TEST_GATED_COMMANDS,');
  lines.push('  replayWhitelist: REPLAY_WHITELIST,');
  lines.push('  isWebCommand,');
  lines.push('  isDesktopOnly,');
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

/** 生成 events.ts 源文本（确定性输出：无时间戳，保持 events.rs 声明序）。 */
export function generateEventsModule(entries) {
  const lines = [];
  lines.push('// AUTO-GENERATED by `npm run gen:transport` —— 请勿手改。');
  lines.push('//');
  lines.push(`// Story 15.5 TS 侧事件名清单（${entries.length} 个）：源 crates/egosync-engine/src/events.rs`);
  lines.push('// （事件名常量唯一发射源；skill-scope-updated 为前端本地事件不入册）。');
  lines.push('// payload 类型维持组件内手写接口现状（15.5 裁量：events.rs 无类型信息）。');
  lines.push('');
  lines.push(`/** 引擎事件名全名单（${entries.length} 个，events.rs 声明序）。 */`);
  lines.push('export const ENGINE_EVENT_NAMES: readonly string[] = [');
  for (const e of entries) lines.push(`  '${e.eventName}',`);
  lines.push('];');
  lines.push('');
  lines.push('/** 引擎事件名字面量联合类型（编译期收窄用）。 */');
  lines.push('export type EngineEventName = (typeof ENGINE_EVENT_NAMES)[number];');
  lines.push('');
  return lines.join('\n');
}

function main() {
  const { commands, replayWhitelist } = readCommandsArtifact();
  const capabilitiesRs = readFileSync(CAPABILITIES_RS, 'utf8');
  const eventsRs = readFileSync(EVENTS_RS, 'utf8');

  const desktopOnly = parseConstList(capabilitiesRs, 'DESKTOP_ONLY_COMMANDS');
  const perfTestGated = parseConstList(capabilitiesRs, 'PERF_TEST_GATED_COMMANDS');
  const reconnectReplay = parseConstList(capabilitiesRs, 'RECONNECT_REPLAY_COMMANDS');

  // 工件与 Rust 单源常量交叉校验：gen_commands 未重跑（capabilities.rs 改了
  // 白名单而工件未再生）即在此响亮失败——防止 TS 生成物基于过期工件静默漂移
  // （Rust 侧新鲜度门禁在 server-ci；此处为本地防线）。
  const sorted = (arr) => [...arr].sort();
  if (JSON.stringify(sorted(reconnectReplay)) !== JSON.stringify(sorted(replayWhitelist))) {
    throw new Error(
      'commands.json 的 replayWhitelist 与 capabilities.rs 的 RECONNECT_REPLAY_COMMANDS 不一致——请先 `cd server && cargo run --features gen --bin gen_commands` 再生成'
    );
  }

  const events = parseEngineEvents(eventsRs);

  const capabilitiesTs = generateCapabilitiesModule({
    commands,
    desktopOnly,
    perfTestGated,
    replayWhitelist,
  });
  const eventsTs = generateEventsModule(events);

  writeFileSync(OUT_CAPABILITIES, capabilitiesTs);
  writeFileSync(OUT_EVENTS, eventsTs);
  console.log(
    `已写出 ${path.relative(appRoot, OUT_CAPABILITIES)}（web-ok ${commands.length} / desktop-only ${desktopOnly.length} / 门控 ${perfTestGated.length} / 白名单 ${replayWhitelist.length}）`
  );
  console.log(`已写出 ${path.relative(appRoot, OUT_EVENTS)}（事件 ${events.length} 个）`);
}

// 仅作 CLI 直跑时执行生成（测试 import 解析器时不产生副作用）
const invokedAsCli =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedAsCli) {
  main();
}
